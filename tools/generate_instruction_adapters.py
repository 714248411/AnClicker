"""Generate adapters and Qt bindings from canonical schemas and Designer sources.

Schema modules and .ui files are maintained inputs, never generator outputs.
"""
from __future__ import annotations
import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

import sys as _import_sys
from pathlib import Path as _ImportPath
if __package__ in (None, ""):
    _import_sys.path.insert(0, str(_ImportPath(__file__).resolve().parents[1]))
from anclicker._imports import DeferredImports as _DeferredImports

# Dependencies declared here retain their existing on-demand loading boundaries.
_module_imports = _DeferredImports(globals(), {
    'anclicker': ('import', 'anclicker', (), False),
    'INSTRUCTION_SPECS': ('from', 'anclicker.instructions.registry', ('INSTRUCTION_SPECS',), 0),
})


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
anclicker = _module_imports.load('anclicker')  # Enable source-tree legacy entry points.
INSTRUCTION_SPECS = _module_imports.load('INSTRUCTION_SPECS')


def selected_specs(family):
    catalog = json.loads((ROOT / 'integrations/yingdao/commands.json').read_text(encoding='utf-8'))
    by_type = {item['type_id']: item for item in catalog}
    for spec in INSTRUCTION_SPECS:
        if family == 'rpa' and spec.type_id in by_type:
            yield spec, by_type[spec.type_id]
        elif family == 'background' and spec.category == '后台功能' and spec.type_id != '后台答题器':
            yield spec, None
        elif family == 'ocr' and spec.category == '本地OCR':
            yield spec, None


def editor_source(spec, command):
    if spec.category == '本地OCR':
        base = 'LocalOcrEditor'
        base_module = 'anclicker.ui.instruction_editors.local_ocr_instruction'
    elif command is not None:
        base = 'RpaInstructionEditor'
        base_module = 'anclicker.ui.instruction_editors.rpa_instruction'
        if spec.type_id == '坐标点击（可多点）':
            base = 'CoordinateClickEditor'
            base_module = 'anclicker.ui.instruction_editors.extensions.coordinate_click'
    else:
        base = {'绑定选择窗口': 'BindingEditor', '解除后台绑定': 'UnbindingEditor'}.get(spec.type_id, 'BackgroundMethodEditor')
        base_module = 'anclicker.ui.instruction_editors.background_instruction'
    source = (
        '"""Generated by tools/generate_instruction_adapters.py; edit schema/UI sources."""\n'
        'from importlib import import_module\n'
        f'from {base_module} import {base}\n'
        f'from {spec.schema_module_path} import FIELDS\n'
        f'from {spec.executor_module_path} import InstructionExecutor\n\n'
        f'Ui_InstructionEditor = import_module({"anclicker.ui.generated." + spec.module_path + "_ui"!r}).Ui_InstructionEditor\n\n'
        f'class InstructionEditor({base}):\n'
        f'    TYPE_ID = {spec.type_id!r}\n'
        f'    DISPLAY_NAME = {spec.display_name!r}\n'
    )
    if command is not None:
        source += f'    COMMAND_ID = {command["id"]!r}\n'
    return source + '    UI_CLASS = Ui_InstructionEditor\n    FIELDS = FIELDS\n'


def generate(family, output_root):
    output_root = Path(output_root)
    generated = []
    compiler = Path(sys.executable).parent / ('pyside2-uic.exe' if sys.platform == 'win32' else 'pyside6-uic')
    if not compiler.exists():
        raise RuntimeError(f'Qt UI compiler missing: {compiler}')
    for spec, command in selected_specs(family):
        target = output_root / (spec.editor_module_path.replace('.', '/') + '.py')
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(editor_source(spec, command), encoding='utf-8', newline='\n')
        generated.append(target.relative_to(output_root))
        ui = Path('resources/ui') / (spec.module_path.replace('.', '/') + '.ui')
        binding = Path('anclicker/ui/generated') / (spec.module_path.replace('.', '/') + '_ui.py')
        destination = output_root / binding
        destination.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run([str(compiler), str(ui), '-o', str(destination)], cwd=ROOT, check=True)
        text = destination.read_text(encoding='utf-8').replace('from PySide2.', 'from anclicker.platform.qt_compat.').replace('from PySide6.', 'from anclicker.platform.qt_compat.')
        destination.write_text(text, encoding='utf-8', newline='\n')
        generated.append(binding)
    return generated


def main(family=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--family', choices=['rpa', 'background', 'ocr'], default=family or 'rpa')
    parser.add_argument('--output-root', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        with tempfile.TemporaryDirectory(prefix='anclicker-codegen-') as directory:
            paths = generate(args.family, directory)
            stale = [str(path) for path in paths if not (ROOT / path).is_file() or
                     (Path(directory) / path).read_text(encoding='utf-8') !=
                     (ROOT / path).read_text(encoding='utf-8')]
        if stale:
            raise SystemExit('Generated files are stale:\n' + '\n'.join(stale))
        print(f'{args.family}: {len(paths)} generated files are current')
    else:
        print(f'{args.family}: generated {len(generate(args.family, args.output_root))} files')


if __name__ == '__main__':
    main()
